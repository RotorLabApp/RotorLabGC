/****************************************************************************
 *
 * RotorLab GC Plan view 3D (G64, MG2) - scene content from a plan.
 *
 * Turns the plan (as MissionController would upload it, plus fence and
 * rally) into the things the 3D view draws: route samples with their
 * section 4 state, height stems, markers, fence prisms and pattern outlines.
 * No Qt Quick here, so the rules can be tested on the corpus without a
 * window. Plan3DSource fills a SourcePlan from a PlanMasterController.
 *
 ****************************************************************************/

#pragma once

#include "Plan3DMath.h"

#include <QtCore/QList>
#include <QtCore/QString>
#include <QtCore/QStringList>

namespace Plan3D {

/// One MAVLink mission item as GC would upload it (VisualMissionItem::appendMissionItems).
struct SourceItem {
    int     seq             = 0;
    int     visualIndex     = 0;        ///< index in MissionController::visualItems
    int     command         = 0;
    int     frame           = 0;
    double  params[7]       = {kNaN, kNaN, kNaN, kNaN, kNaN, kNaN, kNaN};
    int     altitudeMode    = 0;        ///< simple items: GC's AltitudeMode (1..4); 0 when the item has none
    bool    fromComplex     = false;    ///< generated by a survey, corridor, structure scan or landing pattern
    /// G65 (E-2, CL-2): params[6] is a held height while GC's terrain query is
    /// pending: drawn there, but unknown (never classed, no height above ground).
    bool    heightHeld      = false;
    /// G65 (F4): the hold timed out without GC's answer; still unknown.
    bool    heightUnavailable = false;
};

struct SourceFence {
    bool                    inclusion   = true;
    bool                    circle      = false;
    QList<QPair<double, double>> polygon;  ///< lat, lon
    double                  centerLat   = kNaN;
    double                  centerLon   = kNaN;
    double                  radiusM     = 0;
};

struct SourcePoint {
    double lat = kNaN, lon = kNaN, alt = kNaN;
};

struct SourceOutline {
    int                     visualIndex = 0;
    bool                    closed      = true;     ///< polygon (survey, structure) or polyline (corridor)
    QList<QPair<double, double>> path;
};

struct SourcePlan {
    double  homeLat         = kNaN;
    double  homeLon         = kNaN;
    /// H, the plan's own plannedHomePosition[2]: as loaded or typed, never
    /// GC's later overwrite from its terrain query (Plan3DSource captures it).
    double  homeAmsl        = kNaN;
    bool    arduPilot       = false;
    bool    multiRotor      = false;
    bool    fixedWing       = false;    ///< RTL ends over home instead of descending
    bool    vtol            = false;
    /// A-10: the return height above launch, only when it was read from the
    /// aircraft (never from the file, which holds none). NaN: RTL legs are unknown.
    double  rtlReturnRelM   = kNaN;
    QString rtlSource;                  ///< where rtlReturnRelM came from, for the legend
    QList<SourceItem>       items;      ///< in upload order, home (seq 0) excluded
    QList<SourceFence>      fences;
    SourcePoint             breachReturn;   ///< altitude above launch (A-9); lat NaN when not set
    QList<SourcePoint>      rally;          ///< altitude above launch (A-9)
    QList<SourceOutline>    outlines;
    /// Rev 11 section 4b, loiter legs as flown. Test only: false draws the
    /// loiters as before revision 11 (the corpus parity check).
    bool                    loitersAsFlown = true;
};

enum class LineKind {
    Path,           ///< flown route, colored by section 4
    Unknown,        ///< flown route whose height is not in the file (RTL, A-10): always Unknown
    Stem,           ///< height stem down to known ground
    StemUnknown,    ///< height stem over unknown ground: dashed (CL-4)
    FenceInclusion,
    FenceExclusion, ///< fences are prisms without a strike check (CL-7)
    Outline,        ///< survey, corridor and structure footprints on the ground
};

struct LineSeg {
    Vec3        a, b;
    Clearance   clearance   = Clearance::Unknown;   ///< Path only
    LineKind    kind        = LineKind::Path;
    int         visualIndex = -1;
};

enum class MarkerKind {
    Home,
    Waypoint,       ///< a route point from a simple item
    PatternPoint,   ///< a route point generated by a complex item (smaller)
    Roi,
    Rally,
    BreachReturn,
};

struct Marker {
    Vec3        pos;
    MarkerKind  kind        = MarkerKind::Waypoint;
    Clearance   clearance   = Clearance::Unknown;
    int         visualIndex = -1;
    int         seq         = -1;
    int         command     = 0;
    QString     label;
    double      amsl        = kNaN;
    double      ground      = kNaN;
    bool        heightPending = false;  ///< G65: drawn at a held height, unknown until GC answers (CL-2)
    bool        terrainUnavailable = false; ///< G65: GC never answered: stays unknown, "terrain height not available"
};

/// G66 parity: one drawn leg of the checked route, as the samples below
/// refer to it. Ends are the route points the leg is sampled between.
enum class LegShape {
    Straight,       ///< straight AMSL line (A-7)
    Spline,         ///< Catmull-Rom (S-5); t is the curve parameter within the leg
    Terrain,        ///< follows the ground at an interpolated height above it (A-7)
    Ring,           ///< loiter circle; t is the fraction of the turn from angle 0 (east)
    UnknownHeight,  ///< height not in the file (RTL, A-10): every sample Unknown
};

struct SampleLeg {
    double      fromLat = kNaN, fromLon = kNaN, fromAmsl = kNaN;   ///< amsl NaN when unknown
    double      toLat = kNaN,   toLon = kNaN,   toAmsl = kNaN;
    LegShape    shape       = LegShape::Straight;
    bool        contactLeg  = false;    ///< takeoff or landing leg (CL-1a)
    int         command     = 0;        ///< command of the point the leg flies into (0 for a derived point)
    int         visualIndex = -1;       ///< MissionController visual item the leg flies into (0 = home)
};

/// G66 parity: one checked sample, in the state the scene draws it with.
struct PathSample {
    int         leg     = -1;           ///< index into Scene::sampleLegs
    double      t       = 0;            ///< 0..1 along the leg (see LegShape)
    double      lat     = kNaN, lon = kNaN;
    double      amsl    = kNaN;         ///< NaN when the height is unknown
    double      ground  = kNaN;         ///< NaN when the ground is unknown
    Clearance   clearance = Clearance::Unknown;
};

struct Stats {
    int samplesStrike   = 0;            ///< red samples; never includes ground contact
    int samplesGroundContact = 0;       ///< CL-1a: takeoff or landing contact span, HAG -0.5 m to under 2 m; not strikes
    int samplesUnknown  = 0;
    int samplesNoStrike = 0;
    int pointsUnknownGround = 0;
    int skippedCommands = 0;            ///< items with commands 100 or above, not drawn (DO_JUMP loops not checked)
};

struct Scene {
    LocalFrame          frame;
    QList<LineSeg>      lines;
    QList<Marker>       markers;
    Stats               stats;
    QStringList         warnings;
    bool                hasSpline       = false;
    bool                hasTerrainFrame = false;
    bool                hasUnknownRtl   = false;    ///< an RTL leg drawn violet (A-10)
    /// A-0: the launch reference R for every relative height: the loaded
    /// ground at home G(home) when known, else H; NaN when both are missing (A-4).
    double              launchRef       = kNaN;
    bool                launchRefFromGround = false;
    bool                homeDatumNote   = false;    ///< A-0b note shown (|H - G(home)| > kHomeDatumNoteM)
    double              sampleSpacingM  = kMaxSampleSpacingM;   ///< rev 4 S used for this scene
    /// G67 M1: a drawing limit was reached (Plan3DMath.h). Each entry is also
    /// in `warnings`; the view shows them without opening the legend.
    QStringList         limitWarnings;
    bool                overSampleBudget = false;   ///< kMaxSceneSamples reached: the rest is not drawn
    Vec3                boundsMin, boundsMax;
    /// G66 parity: every checked sample with its own state (a drawn segment
    /// takes the worse state of its two ends), and the legs they lie on.
    QList<SampleLeg>    sampleLegs;
    QList<PathSample>   samples;
};

struct GeoBounds {
    double south = kNaN, west = kNaN, north = kNaN, east = kNaN;
    bool valid() const { return std::isfinite(south) && std::isfinite(north) && north >= south; }
};

class Builder
{
public:
    /// Area the plan covers (route, fences, rally, outlines), with a margin of
    /// max(marginM, 15 % of the larger side) on every side.
    static GeoBounds bounds(const SourcePlan &plan, double marginM = 150.0);

    /// Builds the scene. `ground` gives G(p) (NaN when unknown).
    /// `groundCellM` is the loaded ground grid's cell size (rev 4 CL-1); NaN uses the 15 m cap.
    static Scene build(const SourcePlan &plan, const GroundFn &ground, double groundCellM = kNaN);

    /// The smaller node spacing of a ground grid over `area` with `cols` x `rows` nodes, NaN if unknown.
    static double gridCellM(const GeoBounds &area, int cols, int rows);

    /// Commands drawn as route points (positional NAV commands).
    static bool isRoutePoint(int command);
    static bool isTakeoff(int command)   { return command == 22 || command == 84; }
    static bool isLand(int command)     { return command == 21 || command == 85; }
    static bool isLoiter(int command)   { return command == 17 || command == 18 || command == 19 || command == 31; }
    static bool isRtl(int command)      { return command == 20; }
    /// Loiter radius in metres, signed: positive is clockwise (ArduPilot and
    /// GC's landing pattern, LandingComplexItem.cc:414). NaN when none.
    static double loiterRadius(const SourceItem &item);
    static bool isRoi(int command)      { return command == 195 || command == 201; }
};

} // namespace Plan3D
